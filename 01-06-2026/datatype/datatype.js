console.log("Data Type");

// 1.number : int, float
console.log(1);
console.log(3.14);
console.log(typeof 1);
console.log(typeof 3.14);


// 2.string : character, string
console.log("Hello");
console.log('World');
console.log(typeof "Hello");
console.log(typeof 'World');


// 3.boolean : true, false
console.log(true);
console.log(false);
console.log(typeof true);
console.log(typeof false);


// 4.object : array, object
console.log([1, 2, 3]);
console.log({ name: "Hiral"});
console.log(null);
console.log(typeof null);
console.log(typeof [1, 2, 3]);
console.log(typeof { name: "Hiral"});


// 5.undefined : undefined
console.log(undefined);
console.log(typeof undefined);


// 6.BigInt : bigInt
console.log(1234567890123456789012345678901234567890n);
console.log(typeof 1234567890123456789012345678901234567890n);


// 7.Function : function
console.log(typeof console.log);


